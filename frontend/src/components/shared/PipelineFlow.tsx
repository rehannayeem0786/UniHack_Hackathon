const MODEL_BADGE: Record<
  Stage["model"],
  { text: string; variant: "outline" | "primary" | "success" }
> = {
  none: { text: "Deterministic", variant: "outline" },
  picks: { text: "Model picks", variant: "primary" },
  extracts: { text: "Model extracts", variant: "primary" },
  writes: { text: "Formula", variant: "outline" },
  retrieves: { text: "Web retrieval", variant: "success" },
  replays: { text: "Human memory", variant: "outline" },
};

export type StageStatus = "idle" | "active" | "done";

/** Live per-stage state, keyed by stage key, driven by the SSE stream. */
export interface StageState {
  status: StageStatus;
  elapsedMs?: number;
}

export function PipelineFlow({
  status = "idle",
  activeIndex = -1,
  stageStates,
}: {
  status?: StageStatus;
  activeIndex?: number;
  /** Real per-stage state from the stream; overrides the index-based walk. */
  stageStates?: Record<string, StageState>;
}) {
  const anyActive = stageStates
    ? Object.values(stageStates).some((s) => s.status === "active")
    : status === "active";
  const doneCount = stageStates
    ? Object.values(stageStates).filter((s) => s.status === "done").length
    : status === "done"
      ? STAGES.length
      : Math.max(activeIndex, 0);

  return (
    <div>
      <div className="mb-3 flex items-center justify-between gap-2">
        <p className="text-xs font-medium uppercase tracking-wide text-muted-foreground">
          {STAGES.length} agents · {doneCount} complete
        </p>
        {anyActive ? (
          <span className="flex items-center gap-1.5 text-xs font-medium text-primary">
            <span className="relative flex size-1.5" aria-hidden>
              <span className="absolute inline-flex size-full animate-ping rounded-full bg-primary opacity-70" />
              <span className="relative inline-flex size-1.5 rounded-full bg-primary" />
            </span>
            Live
          </span>
        ) : null}
      </div>

      <ol className="space-y-2" aria-label="Enrichment pipeline stages">
        {STAGES.map((stage, index) => {
          const live = stageStates?.[stage.key];
          const isDone = live
            ? live.status === "done"
            : status === "done" || (status === "active" && index < activeIndex);
          const isActive = live
            ? live.status === "active"
            : status === "active" && index === activeIndex;
          const badge = MODEL_BADGE[stage.model];

          return (
            <motion.li
              key={stage.key}
              initial={{ opacity: 0, x: -8 }}
              animate={{ opacity: 1, x: 0 }}
              transition={{ duration: 0.3, delay: index * 0.05 }}
              className={cn(
                "flex gap-3 rounded-lg border p-3 transition-colors duration-300",
                isActive
                  ? "border-primary/50 bg-primary/[0.07] shadow-glow"
                  : isDone
                    ? "border-success/25 bg-success/[0.04]"
                    : "border-border/60 bg-surface/40",
              )}
            >
              <div
                className={cn(
                  "mt-0.5 flex size-7 shrink-0 items-center justify-center rounded-md border transition-colors duration-300",
                  isDone
                    ? "border-success/40 bg-success/15 text-success"
                    : isActive
                      ? "animate-pulse-ring border-primary/50 bg-primary/15 text-primary"
                      : "border-border bg-secondary text-muted-foreground",
                )}
                aria-hidden
              >
                {isDone ? (
                  <Check className="size-3.5" />
                ) : isActive ? (
                  <Loader2 className="size-3.5 animate-spin" />
                ) : (
                  <stage.icon className="size-3.5" />
                )}
              </div>

              <div className="min-w-0 flex-1 space-y-1">
                <div className="flex flex-wrap items-center gap-2">
                  <p className="text-sm font-medium leading-none">
                    <span className="tabular mr-1.5 text-muted-foreground">{index + 1}.</span>
                    {stage.title}
                  </p>
                  <Badge variant={badge.variant} className="text-[0.625rem]">
                    {badge.text}
                  </Badge>
                  {isDone && live?.elapsedMs !== undefined ? (
                    <span className="tabular ml-auto text-[0.6875rem] text-muted-foreground">
                      {duration(live.elapsedMs)}
                    </span>
                  ) : null}
                </div>
                <p className="text-xs leading-relaxed text-muted-foreground">{stage.detail}</p>
              </div>
            </motion.li>
          );
        })}
      </ol>
    </div>
  );
}
