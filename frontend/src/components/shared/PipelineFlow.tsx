import { duration } from "@/lib/format";
import { cn } from "@/lib/utils";

interface Stage {
  key: string;
  title: string;
  detail: string;
  icon: LucideIcon;
  model: "none" | "picks" | "extracts" | "writes" | "retrieves" | "replays";
}

